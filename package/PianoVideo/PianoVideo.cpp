  gArgs.mmcxFloor = requestedFloor < kMmcxDisplayFloor ? kMmcxDisplayFloor : requestedFloor;
  gEnc.enabled = bootArg("piano-video-enc", 0) == 1 && enc::bootEnabled(PE_boot_args());
