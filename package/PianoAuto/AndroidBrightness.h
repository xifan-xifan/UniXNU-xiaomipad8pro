static inline uint16_t pa_sdr_code_at_dbv(uint16_t dbv)
{
    const unsigned end = sizeof pa_sdr_points / sizeof pa_sdr_points[0] - 1;
    if (dbv >= PA_SDR_MAX_DBV) return PA_SDR_MAX_CODE;
    unsigned lo = 0, hi = end;
    while (hi - lo > 1) {
        const unsigned mid = lo + (hi - lo) / 2;
        if (pa_sdr_points[mid][0] <= dbv) lo = mid;
        else hi = mid;
    }
    const uint16_t span = pa_sdr_points[hi][0] - pa_sdr_points[lo][0];
    return pa_sdr_points[lo][1] + ((dbv - pa_sdr_points[lo][0]) *
           (pa_sdr_points[hi][1] - pa_sdr_points[lo][1]) + span / 2) / span;
}

/* Loaded 2..600 declared-nit segment: normalized DBV fractions .001709819 and
 * .499755740, times 4095, rounded to millionths of one DBV. */
#define PA_SDR_DBV_OFFSET 7001709ull
#define PA_SDR_DBV_SPAN 2039498046ull

static inline uint16_t pa_sdr_dbv(uint32_t nits_fixed)
{
    if (nits_fixed >= PA_SDR_MAX_FIXED) return PA_SDR_MAX_DBV;
    if (nits_fixed <= (2u << 16)) return PA_SDR_MIN_DBV;
    const uint64_t span = 598ull << 16;
    const uint64_t dbv = (PA_SDR_DBV_OFFSET * span + (nits_fixed - (2u << 16)) * PA_SDR_DBV_SPAN +
                          500000 * span) / (1000000 * span);
    return dbv < PA_SDR_MIN_DBV ? PA_SDR_MIN_DBV : (uint16_t)dbv;
}

static inline uint16_t pa_sdr_code(uint32_t nits_fixed)
{
    return pa_sdr_code_at_dbv(pa_sdr_dbv(nits_fixed));
}

/* The same quantized mapping inverted. Take the midpoint of a plateau in DBV
 * space, or interpolate between adjacent DBVs when the code was skipped.
 * The calibrated interval pins the first lit DBV and the exact SDR endpoint. */
static inline uint32_t pa_sdr_fixed_for_code(uint16_t code)
{
    if (code >= PA_SDR_MAX_CODE) return PA_SDR_MAX_FIXED;
    uint32_t dbv_micro = PA_SDR_MIN_DBV * 1000000u;
    if (code > PA_SDR_MIN_CODE) {
        uint16_t lo = PA_SDR_MIN_DBV, hi = PA_SDR_MAX_DBV;
        while (hi - lo > 1) {
            const uint16_t mid = lo + (hi - lo) / 2;
            if (pa_sdr_code_at_dbv(mid) < code) lo = mid;
            else hi = mid;
        }
        const uint16_t low_code = pa_sdr_code_at_dbv(lo);
        const uint16_t high_code = pa_sdr_code_at_dbv(hi);
        if (high_code != code) {
            const uint16_t span = high_code - low_code;
            dbv_micro = lo * 1000000u + ((code - low_code) * 1000000u + span / 2) / span;
        } else {
            const uint16_t first = hi;
            lo = first;
            hi = PA_SDR_MAX_DBV;
            while (hi - lo > 1) {
                const uint16_t mid = lo + (hi - lo) / 2;
                if (pa_sdr_code_at_dbv(mid) == code) lo = mid;
                else hi = mid;
            }
            dbv_micro = (first + lo) * 500000u;
        }
    }
    return (2u << 16) + (uint32_t)(((dbv_micro - PA_SDR_DBV_OFFSET) * (598ull << 16) +
                                   PA_SDR_DBV_SPAN / 2) / PA_SDR_DBV_SPAN);
}

static inline uint32_t pa_sdr_millinits(uint32_t nits_fixed)
{
    return (uint32_t)(((uint64_t)nits_fixed * 1000 + 32768) >> 16);
}

/* Round the advertised floor up to whole millinits. The native API reads it
 * back as nits and truncates signed 16.16; use that same representable bound. */
static inline uint32_t pa_sdr_floor_fixed(uint16_t floor)
{
    const uint64_t milli = ((uint64_t)pa_sdr_fixed_for_code(floor) * 1000 + 65535) >> 16;
    return (uint32_t)((milli << 16) / 1000);
}

static inline uint32_t pa_sdr_linear_fixed(uint16_t floor, uint16_t code)
{
    const uint32_t lo = pa_sdr_floor_fixed(floor), span = PA_SDR_MAX_CODE - floor;
    if (code <= floor) return lo;
    if (code >= PA_SDR_MAX_CODE) return PA_SDR_MAX_FIXED;
    return lo + (uint32_t)(((uint64_t)(PA_SDR_MAX_FIXED - lo) * (code - floor) + span / 2) / span);
}

static inline uint32_t pa_sdr_permille(uint16_t code)
{
    return (code * 1000u + 1023) / 2047;
}

